"""Generate src/boot_anim_assets.h for the power-on intro.

Inputs (made from the source logo PNG and the reference video's audio track):
  logo565.raw   W*H RGB565 little-endian, alpha already blended over black
  audio.s16     mono int16 little-endian PCM at 22050 Hz (whole track)

The chime is cut from its onset (first sample above ~4.5% of full scale),
minus 5 ms, to where it has decayed below 0.4% of its peak, plus a 40 ms
linear fade so playback never ends on a non-zero sample (a click on the
MAX98357A when the I2S clock stops).

Usage:
  python tools/make_boot_anim_assets.py logo565.raw 150 39 audio.s16 src/boot_anim_assets.h
"""
import struct
import sys

SR = 22050


def main():
    logo_path, w, h, audio_path, out_path = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), sys.argv[4], sys.argv[5]

    raw = open(logo_path, "rb").read()
    assert len(raw) == 2 * w * h, "logo size mismatch"
    px = struct.unpack("<%dH" % (w * h), raw)

    d = open(audio_path, "rb").read()
    a = list(struct.unpack("<%dh" % (len(d) // 2), d))
    onset = next(i for i, v in enumerate(a) if abs(v) > 1500)
    peak = max(abs(v) for v in a)
    end = max(i for i, v in enumerate(a) if abs(v) > peak * 0.004)
    start = max(0, onset - SR * 5 // 1000)
    fade = SR * 40 // 1000
    clip = a[start:end + fade]
    for i in range(fade):
        k = len(clip) - fade + i
        clip[k] = int(clip[k] * (fade - 1 - i) / fade)

    with open(out_path, "w", newline="\n") as f:
        f.write("// Generated by tools/make_boot_anim_assets.py -- do not edit.\n")
        f.write("// Power-on intro: ArcadeFun logo + chime.\n")
        f.write("#ifndef BOOT_ANIM_ASSETS_H\n#define BOOT_ANIM_ASSETS_H\n\n#include <stdint.h>\n\n")
        f.write("#define BOOT_LOGO_W %d\n#define BOOT_LOGO_H %d\n\n" % (w, h))
        f.write("// RGB565, alpha blended over black.\n")
        f.write("static const uint16_t boot_logo_565[BOOT_LOGO_W * BOOT_LOGO_H] = {\n")
        for i in range(0, len(px), 12):
            f.write("    " + ", ".join("0x%04X" % v for v in px[i:i + 12]) + ",\n")
        f.write("};\n\n")
        f.write("#define BOOT_CHIME_RATE %d\n#define BOOT_CHIME_LEN  %d\n\n" % (SR, len(clip)))
        f.write("// Mono signed 16-bit PCM, %.3f s.\n" % (len(clip) / SR))
        f.write("static const int16_t boot_chime[BOOT_CHIME_LEN] = {\n")
        for i in range(0, len(clip), 16):
            f.write("    " + ", ".join(str(v) for v in clip[i:i + 16]) + ",\n")
        f.write("};\n\n#endif // BOOT_ANIM_ASSETS_H\n")
    print("logo %dx%d, chime %d samples (%.3f s) from %.3f s" % (w, h, len(clip), len(clip) / SR, start / SR))


if __name__ == "__main__":
    main()
